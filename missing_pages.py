#!/usr/bin/env python3
"""Turn a QA run into doc/missing_pages.md.

QA prints one "<tractate> <page>" line per page it could not find, then a
summary. This groups those by tractate and collapses consecutive pages into
ranges, so the result reads as "what is left to write" rather than as 367
loose numbers.

    missing_pages.py target/qa.txt > doc/missing_pages.md
"""
import collections
import re
import sys


def ranges(pages):
    """[2,3,4,9,11,12] -> '2-4, 9, 11-12'"""
    out = []
    start = prev = pages[0]
    for p in pages[1:] + [None]:
        if p == prev + 1:
            prev = p
            continue
        out.append(str(start) if start == prev else "%d-%d" % (start, prev))
        start = prev = p
    return ", ".join(out)


def main(path):
    missing = collections.defaultdict(list)
    for line in open(path, encoding="utf-8"):
        line = line.strip()
        if not line or line.startswith("Missing "):
            continue
        m = re.match(r"^(.*) (\d+)$", line)
        if m:
            missing[m.group(1)].append(int(m.group(2)))

    total = sum(len(v) for v in missing.values())
    print("# Missing pages")
    print()
    print("Pages the blog does not have, so the site cannot show them. These are")
    print("genuine gaps in what has been written, not crawler failures.")
    print()
    print("Generated by `publish.sh` from the QA run; do not edit by hand.")
    print()
    print("**%d pages missing across %d tractates.**" % (total, len(missing)))
    print()
    for tractate, pages in sorted(missing.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        pages.sort()
        print("## %s (%d)" % (tractate, len(pages)))
        print()
        print(ranges(pages))
        print()


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "target/qa.txt")
