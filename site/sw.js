// Talmud Illuminated -- service worker.
//
// Copied to site/sw.js by MakeSite, which replaces ti-058e986d with a
// hash of the search index. The version therefore changes when, and only when,
// the site's content changes: readers get new dapim promptly, and a rebuild
// that produced identical content does not invalidate anyone's cache.
//
// What this buys the reader: a daf they have opened stays readable with no
// network, artwork included. That is the point -- the Talmud gets studied on
// trains, in shuls, and in other places with no usable signal.

const VERSION = 'ti-058e986d';
const SHELL = VERSION + '-shell';   // home, search, stylesheet, icons
const PAGES = VERSION + '-pages';   // daf pages the reader has opened
const ART   = VERSION + '-art';     // Blogger-hosted illustrations

const SHELL_URLS = [
  '/index.html',
  '/style.css',
  '/search.html',
  '/offline.html',
  '/icon-192.png',
  '/icon-512.png'
];

self.addEventListener('install', function (event) {
  event.waitUntil(
    caches.open(SHELL).then(function (cache) {
      // cache.addAll is all-or-nothing; a single 404 would wedge installation,
      // so add them one at a time and tolerate individual failures.
      return Promise.all(SHELL_URLS.map(function (url) {
        return cache.add(url).catch(function () { /* keep going */ });
      }));
    }).then(function () { return self.skipWaiting(); })
  );
});

self.addEventListener('activate', function (event) {
  event.waitUntil(
    caches.keys().then(function (keys) {
      return Promise.all(keys.filter(function (k) {
        return k.indexOf(VERSION) !== 0;
      }).map(function (k) {
        return caches.delete(k);
      }));
    }).then(function () { return self.clients.claim(); })
  );
});

// On a reader's first visit the worker is still installing while the page is
// being fetched, so that navigation is never intercepted and the daf they are
// actually reading would be the one page missing offline. pwa.js asks for it
// explicitly once the worker is running.
self.addEventListener('message', function (event) {
  var data = event.data || {};
  if (data.type !== 'cache-page' || !data.url) return;
  event.waitUntil(
    caches.open(PAGES).then(function (cache) {
      return cache.match(data.url).then(function (hit) {
        if (hit) return null;             // already stored; do not refetch
        return cache.add(data.url).catch(function () { /* offline already */ });
      });
    })
  );
});

function isImagePath(pathname) {
  return /\.(jpe?g|png|gif|webp)$/i.test(pathname);
}

self.addEventListener('fetch', function (event) {
  var request = event.request;
  if (request.method !== 'GET') return;

  var url = new URL(request.url);
  var sameOrigin = (url.origin === self.location.origin);

  // Artwork lives on Blogger. These come back opaque, which means we cannot
  // inspect them -- fine here, since they are only ever handed to an <img>.
  if (!sameOrigin) {
    if (isImagePath(url.pathname)) {
      event.respondWith(
        caches.open(ART).then(function (cache) {
          return cache.match(request).then(function (hit) {
            if (hit) return hit;
            return fetch(request).then(function (res) {
              cache.put(request, res.clone());
              return res;
            }).catch(function () {
              return Response.error();
            });
          });
        })
      );
    }
    return; // everything else cross-origin: leave it to the network
  }

  // The search index is regenerated by every crawl and is large. Always live.
  if (url.pathname === '/search-index.json') return;

  // Pages: network first, so a re-crawled daf shows its new text; fall back to
  // the stored copy, and finally to the offline notice.
  if (request.mode === 'navigate' || request.destination === 'document') {
    event.respondWith(
      fetch(request).then(function (res) {
        var copy = res.clone();
        caches.open(PAGES).then(function (c) { c.put(request, copy); });
        return res;
      }).catch(function () {
        return caches.match(request).then(function (hit) {
          return hit || caches.match('/offline.html');
        });
      })
    );
    return;
  }

  // Stylesheet, icons, scripts: cache first, they change rarely.
  event.respondWith(
    caches.match(request).then(function (hit) {
      if (hit) return hit;
      return fetch(request).then(function (res) {
        var copy = res.clone();
        caches.open(SHELL).then(function (c) { c.put(request, copy); });
        return res;
      });
    })
  );
});
